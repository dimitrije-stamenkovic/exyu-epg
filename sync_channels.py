#!/usr/bin/env python3
"""
Extract EX-YU channel names from the provider playlist into channels.txt.

channels.txt is committed, so the GitHub Action can build the EPG without
access to the provider. Re-run this after refreshing my_playlist.m3u.

Usage:
    python sync_channels.py [path/to/my_playlist.m3u]
"""

import re
import sys
from pathlib import Path

DEFAULT_PLAYLIST = Path(__file__).parent.parent / "scripts" / "my_playlist.m3u"
OUTPUT_FILE = Path(__file__).with_name("channels.txt")

# Same live groups as GROUP_FILTERS in scripts/iptv.py
GROUPS = [
    "RS: SERBIA [1080p]",
    "RS: SERBIA [EXTRA]  [1080p]",
    "BH: BOSNIA [1080p]",
    "BH: BOSNIA [EXTRA]  [1080p]",
    "CG: MONTENEGRO [1080p]",
    "CG: MONTENEGRO [EXTRA] [1080p]",
    "CG: MONTENEGRO/CRNA GORA [EXTRA]  [1080p]",
    "HR: CROATIA [1080p]",
    "HR: CROATIA [EXTRA]  [1080p]",
    "MK: MACEDONIA [1080p]",
    "MK: MACEDONIA [EXTRA]  [1080p]",
    "SL: SLOVENIA [1080p]",
    "SL: SLOVENIA [EXTRA]  [1080p]",
    "EXYU: BALKAN SKY [24/7 O-D] [1080p]",
    "EXYU: DECIJI KANALI [1080p]",
    "EXYU: DOKUMENTARNI [1080p]",
    "EXYU: FILMSKI KANALI [1080p]",
    "EXYU: MUZICKI KANALI [1080p]",
    "EXYU: PINK MEDIA [1080p]",
    "EXYU: SKY KIDS [1080p]",
    "EXYU: SPORTSKI KANALI [1080p]",
    "EXYU: [24/7 O-D] [1080p]",
]


def attr(line, name):
    match = re.search(rf'{name}="([^"]*)"', line)
    return match.group(1) if match else ""


def main():
    playlist = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_PLAYLIST
    channels = {}  # name -> tvg-id, keeps playlist order and drops duplicates
    found_groups = set()

    with open(playlist, encoding="utf-8") as f:
        for line in f:
            if not line.startswith("#EXTINF"):
                continue
            group = attr(line, "group-title")
            if group not in GROUPS:
                continue
            found_groups.add(group)
            name = attr(line, "tvg-name") or line.rsplit(",", 1)[-1].strip()
            # Separator entries like "✶⋆✶ SLOVENIA ✶⋆✶" carry no programme
            if "✶" in name:
                continue
            tvg_id = attr(line, "tvg-id")
            channels.setdefault(name, "" if tvg_id == "None" else tvg_id)

    for group in GROUPS:
        if group not in found_groups:
            print(f"Warning: group not found in playlist: {group!r}")

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write("# Playlist channel name<TAB>tvg-id, generated by sync_channels.py\n")
        for name, tvg_id in channels.items():
            f.write(f"{name}\t{tvg_id}\n")
    print(f"Wrote {len(channels)} channels to {OUTPUT_FILE.name}")


if __name__ == "__main__":
    main()
